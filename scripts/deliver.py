"""deliver.py — one-command delivery: measure the gate → no film on red; on green or yellow copy the film and write delivery notes whose facts are written by the script.

    uv run deliver.py <film.mp4> --out output/ [--spec clip.json | --project <engine project>] [--qa <qa output dir>] [--root <project dir>]
                      [--sub-band 0.15] [--vertical auto|yes|no] [--allow-blue-purple "reason"]
    uv run deliver.py --verify output/delivery-notes.md       # check whether the facts section has been edited

It does three things:
  1. Runs film_gate.py from the same directory. On red: doesn't copy the film or write notes, prints the reason and the fix, exit code 2.
  2. On green or yellow: copies the film to --out and writes --out/delivery-notes.md. The facts section is written entirely by the script:
     duration, resolution, frame rate, audio track, file fingerprint; every gate metric and light; the worst 30-second window;
     whether QA was run and its results (reads qa.json in the QA output directory, writing "not run" if absent);
     whether there is an independent review record (whether <project dir>/review/*.md exists, listing filenames; otherwise "no reviewer sent").
  3. The facts section ends with a fingerprint. The maker fills in only subjective notes in the "Production notes" section (which grammar was used,
     why each yellow item is acceptable, a self-check against the six ways to get it wrong), without editing the facts section; --verify reports any edits.

Conventions:
  - QA output directory: --qa first; otherwise the same as qa.py's default — --spec → <spec dir>/qa, --project → <engine project parent>/qa.
  - Project directory: --root first; otherwise the parent of --project; otherwise the --spec directory; otherwise the film's directory.
  - The reviewer (an agent or person not involved in making it) writes conclusions as <project dir>/review/<any name>.md. The script only checks
    that the files exist; it doesn't read the content or draw conclusions on the reviewer's behalf.
"""
from __future__ import annotations

import argparse
import datetime
import hashlib
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import film_gate  # noqa: E402

DOC = "delivery-notes.md"
REVIEW_DIR = "review"
START = "<!-- deliver.py facts section: start. This section is generated by the script; don't edit it, or deliver.py --verify will report it -->"
END_RE = re.compile(r"<!-- deliver\.py facts section: end sha256=([0-9a-f]{64}) -->")
LIGHT_NAME = {"red": "red light", "yellow": "yellow light", "green": "green light", "--": ""}


def probe(path):
    out = subprocess.check_output(["ffprobe", "-v", "error", "-show_entries",
                                   "stream=codec_type,codec_name,width,height,avg_frame_rate:format=duration",
                                   "-of", "json", str(path)])
    j = json.loads(out)
    v = next(s for s in j["streams"] if s.get("codec_type") == "video")
    a = [s for s in j["streams"] if s.get("codec_type") == "audio"]
    num, _, den = (v.get("avg_frame_rate") or "0/1").partition("/")
    fps = float(num) / float(den or 1) if float(den or 1) else 0.0
    return {"duration": float(j["format"].get("duration") or 0), "width": v["width"], "height": v["height"],
            "fps": round(fps, 3), "vcodec": v.get("codec_name"), "audio": a[0].get("codec_name") if a else None}


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def stamp(p):
    return datetime.datetime.fromtimestamp(p.stat().st_mtime).strftime("%Y-%m-%d %H:%M:%S")


def qa_facts(qa_dir, spec):
    """Reads qa.py's output. Returns fact lines (a list)."""
    if qa_dir is None:
        return ["- Not run (no --spec / --project / --qa given, so there's no way to know where to find the QA output)"]
    f = qa_dir / "qa.json"
    if not f.is_file():
        return [f"- Not run ({f} doesn't exist)"]
    try:
        r = json.loads(f.read_text())
    except (ValueError, OSError) as e:
        return [f"- Can't read qa.json: {f} ({type(e).__name__}); counted as not run"]
    segs = r.get("segments", [])
    det = sum(1 for s in segs if s.get("deterministic"))
    spikes = sum(len(s.get("spikes_at_lt", [])) for s in segs)
    cams = sum(len(s.get("camera_events_lt", [])) for s in segs)
    framing = sum(len(s.get("framing", [])) for s in segs)
    errs = r.get("page_errors", [])
    L = [f"- Run: `{f}` (written at {stamp(f)})",
         f"- {len(errs)} page errors" + (" (QA counts this as a failure)" if errs else ""),
         f"- Determinism: {det}/{len(segs)} segments pixel-identical",
         f"- {spikes} jumps" + (f"; plus {cams} camera events (monotonic, smooth push/pulls or pans within 2 seconds, not counted as jumps)" if "camera_events_lt" in (segs[0] if segs else {}) else ""),
         f"- {framing} framing cues (cut-off text, overlapping text, entering the subtitle band, near-blank; they mean \"go look at this frame\", not errors)"]
    for s in segs:
        L.append(f"  - {s.get('id')}: motion {s.get('motion_pct')}%, static frame pairs {s.get('still_pairs_pct')}%, "
                 f"jumps {len(s.get('spikes_at_lt', []))}, {s.get('ms_mean')}/{s.get('ms_max')} ms/frame")
    if spec is not None and r.get("spec") and Path(r["spec"]).resolve() != spec.resolve():
        L.append(f"- Note: this qa.json measured a different spec ({r['spec']}), not {spec}")
    if spec is not None and spec.is_file() and spec.stat().st_mtime > f.stat().st_mtime:
        L.append(f"- Note: the spec was changed after QA (spec written at {stamp(spec)}), so these QA results may be stale")
    return L


def review_facts(root):
    d = root / REVIEW_DIR
    files = sorted(p.name for p in d.glob("*.md")) if d.is_dir() else []
    if not files:
        return [f"- No reviewer sent (no .md files under `{d}`)"]
    return [f"- {len(files)} review record(s) (`{d}`): " + ", ".join(files),
            "- The script only confirmed the files exist and didn't read them; the files themselves are the review conclusions"]


def facts_block(src, dst, info, res, rows, qa_lines, rv_lines):
    ex = res["explain"]
    gl = res["gate_light"]
    L = ["## Facts (written by deliver.py)", "",
         f"- Generated at: {datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
         f"- Film: `{dst.name}` (sha256 {sha256(dst)[:16]}; source file `{src}`)",
         f"- Duration {info['duration']:.2f}s | {info['width']}×{info['height']} | {info['fps']:g}fps | video {info['vcodec']} | "
         f"audio: {info['audio'] or 'none'}",
         "", "### Gate (film_gate)", "",
         f"- Verdict: {LIGHT_NAME[gl]}. Fast-motion frame ratio {res['fast_ratio']} (< 0.035 red, < 0.06 yellow)",
         f"- In one sentence: {ex['summary']}." + ("; ".join(ex["why"]) + "." if ex["why"] else "")]
    if res.get("allow_blue_purple"):
        L.append(f"- The maker states the topic needs blue-purple (blue-purple gate downgraded to yellow): {res['allow_blue_purple']}; "
                 f"blue-purple background {res['blue_purple_share']:.0%}")
    if ex["worst_window"]:
        w = ex["worst_window"]
        L.append(f"- Worst {w['end_s'] - w['start_s']:.0f}-second window: {w['start_s']:.0f}–{w['end_s']:.0f}s, fast-motion ratio {w['fast_ratio']}")
    if ex["fix"]:
        L.append(f"- How to fix: {ex['fix']}")
    L += ["", "| Light | Type | Metric | Value |", "|---|---|---|---|"]
    for k, name, v, lv, gate, unit in rows:
        vs = "—" if v is None else (f"{v:.3f}" if isinstance(v, float) else str(v))
        L.append(f"| {LIGHT_NAME[lv] or 'number only'} | {'gate' if gate else 'report'} | {name} | {vs}{unit} |")
    L += ["", "### QA", ""] + qa_lines + ["", "### Independent review", ""] + rv_lines
    return "\n".join(L) + "\n"


def write_doc(out, dst, facts, res):
    h = hashlib.sha256(facts.encode()).hexdigest()
    look = [t for _, t in res["explain"]["look"]]
    if res["lights"]["fast_ratio"] == "yellow":
        look.insert(0, f"Gate yellow light: fast-motion frame ratio {res['fast_ratio']} (yellow line 0.06)")
    tail = ["## Production notes (filled in by the maker; write only in this section, don't touch the facts section)", "",
            "- Which grammar / style was used:",
            "- Self-check against the \"six ways to get it wrong\", item by item:",
            "- Each yellow item explained (timecode + why it's acceptable):" + ("" if look else " no yellow items")]
    tail += [f"  - {t}:" for t in look]
    doc = f"# Delivery notes: {dst.name}\n\n{START}\n{facts}<!-- deliver.py facts section: end sha256={h} -->\n\n" + "\n".join(tail) + "\n"
    (out / DOC).write_text(doc)
    return out / DOC


def verify(path):
    t = Path(path).read_text()
    i = t.find(START)
    m = END_RE.search(t)
    if i < 0 or not m or m.start() < i:
        print(f"❌ {path}: can't find the start/end markers of the facts section (deleted, or not written by deliver.py)"); return 3
    facts = t[i + len(START) + 1: m.start()]
    if hashlib.sha256(facts.encode()).hexdigest() != m.group(1):
        print(f"❌ {path}: the facts section has been edited and doesn't match what deliver.py wrote. Rerun deliver.py to regenerate it."); return 3
    print(f"✓ {path}: the facts section matches what deliver.py wrote"); return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("mp4", nargs="?")
    ap.add_argument("--out", help="delivery directory (e.g., output/)")
    ap.add_argument("--spec", help="parameterized clip spec (used to find the QA output: <spec dir>/qa)")
    ap.add_argument("--project", help="engine project directory (used to find the QA output: <engine project parent>/qa)")
    ap.add_argument("--qa", help="QA output directory (when qa.py --out wrote somewhere else)")
    ap.add_argument("--root", help=f"project directory (where {REVIEW_DIR}/*.md is looked for)")
    ap.add_argument("--sub-band", type=float, default=None, help="same as film_gate.py: fraction of the bottom subtitle band to mask")
    ap.add_argument("--vertical", default="auto", choices=["auto", "yes", "no"])
    ap.add_argument("--verify", metavar=DOC, help="only check whether the facts section has been edited")
    ap.add_argument("--allow-blue-purple", metavar="REASON", default=None,
                    help="same as film_gate.py: when the topic itself needs blue-purple, give a reason, which is written into the delivery notes' facts section")
    a = ap.parse_args()
    if a.verify:
        sys.exit(verify(a.verify))
    if not a.mp4 or not a.out:
        ap.error("give the film and --out")
    src = Path(a.mp4).resolve()
    if not src.is_file():
        print(f"Film doesn't exist: {src}", file=sys.stderr); sys.exit(1)
    if not shutil.which("ffmpeg") or not shutil.which("ffprobe"):
        print("ffmpeg/ffprobe required", file=sys.stderr); sys.exit(1)
    spec = Path(a.spec).resolve() if a.spec else None
    proj = Path(a.project).resolve() if a.project else None
    qa_dir = Path(a.qa).resolve() if a.qa else spec.parent / "qa" if spec else proj.parent / "qa" if proj else None
    root = Path(a.root).resolve() if a.root else proj.parent if proj else spec.parent if spec else src.parent

    try:
        info = probe(src)
        res, rows = film_gate.measure(str(src), sub_band=a.sub_band, vertical=a.vertical, allow_blue_purple=a.allow_blue_purple)
    except (subprocess.CalledProcessError, StopIteration, KeyError, RuntimeError, ValueError) as e:
        print(f"Can't read this film: {src} ({e})", file=sys.stderr); sys.exit(1)
    print("\n".join(film_gate.report_lines(res, rows)))
    ex = res["explain"]
    if res["verdict"] == "red":
        print(f"\n❌ Red light, not delivered: {ex['summary']}." + ("; ".join(ex["why"]) + "." if ex["why"] else ""))
        print("How to fix: " + ex["fix"])
        print(f"The film was not copied and {DOC} was not written. Fix it, re-render, and run deliver.py again.")
        sys.exit(2)

    out = Path(a.out).resolve()
    out.mkdir(parents=True, exist_ok=True)
    dst = out / src.name
    if dst != src:
        shutil.copy2(src, dst)
    qa_lines, rv_lines = qa_facts(qa_dir, spec), review_facts(root)
    facts = facts_block(src, dst, info, res, rows, qa_lines, rv_lines)
    doc = write_doc(out, dst, facts, res)
    gl = res["gate_light"]
    print(f"\n{'✓ Green light' if gl == 'green' else '⚠ Yellow light'}, delivered: {dst}")
    print(f"Delivery notes: {doc} (the facts section is written by the script; add subjective notes only in the \"Production notes\" section)")
    print("QA: " + qa_lines[0][2:])
    print("Review: " + rv_lines[0][2:])
    if ex["look"]:
        print("Yellow items need a timecode and reason each in the delivery notes: " + "; ".join(t for _, t in ex["look"]))
    sys.exit(0)


if __name__ == "__main__":
    main()
